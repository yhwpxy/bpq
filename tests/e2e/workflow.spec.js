import { test, expect } from '@playwright/test';
import { LOGIN_SPEC } from '../../shared/example.js';
test('TC-01~03 / TC-06 / TC-08~10 规格编辑生成执行持久化与离线依赖',async({page})=>{
 const errors=[],external=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 page.on('request',r=>{if(!/^https?:\/\/(127\.0\.0\.1|localhost)(:|\/)/.test(r.url())&&!r.url().startsWith('data:'))external.push(r.url());});
 // Block external networking while leaving the two local processes reachable.
 await page.route('**/*',route=>/^https?:\/\/(127\.0\.0\.1|localhost)(:|\/)/.test(route.request().url())?route.continue():route.abort());
 await page.goto('/');
 await page.getByRole('button',{name:'导入规格',exact:true}).click();
 await page.locator('#spec-text').fill(LOGIN_SPEC);
 await page.getByRole('button',{name:'开始分解',exact:true}).click();
 await expect(page.getByText('Markdown 已识别')).toBeVisible();
 await expect(page.locator('.task-table tbody tr')).toHaveCount(9);
 await page.locator('.preview-name input').fill(`E2E 工作流 ${Date.now()}`);
 await page.getByRole('textbox',{name:'1.1 名称',exact:true}).fill('用户名格式检查');
 await page.getByRole('button',{name:'确认并生成画布',exact:true}).click();
 await expect(page.locator('.node-count')).toHaveText('11 节点 · 12 连线');
 await expect(page.locator('.x6-node')).toHaveCount(11);
 await expect(page.locator('.x6-node').filter({hasText:'用户名格式检查'})).toHaveCount(1);
 await page.getByRole('button',{name:'执行编排',exact:true}).click();
 await expect(page.locator('.canvas-run-badge')).toContainText('运行中');
 await expect(page.locator('.canvas-run-badge')).toContainText('执行成功',{timeout:15000});
 await expect(page.locator('.log-panel')).toContainText('跳过');
 const draft=await page.evaluate(()=>JSON.parse(localStorage.getItem('vto.plan.draft.v1')));
 const run=await page.evaluate(()=>JSON.parse(localStorage.getItem('vto.run.v1')));
 const result=await (await page.request.get(`/api/runs/${run.runId}`)).json();
 expect(result.status).toBe('SUCCESS');expect(Object.values(result.nodeStates).filter(s=>s.status==='SKIPPED')).toHaveLength(1);
 await page.reload();await expect(page.locator('.x6-node')).toHaveCount(11);
 await expect(page.locator('.canvas-run-badge')).toContainText('执行成功');
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('vto.plan.draft.v1')).plan)).toEqual(draft.plan);
 await page.getByRole('button',{name:'方案',exact:true}).click();
 await expect(page.locator('.saved-plan').filter({hasText:draft.plan.name})).toHaveCount(1);
 await page.locator('.saved-plan').filter({hasText:draft.plan.name}).getByRole('button',{name:'打开',exact:true}).click();
 await expect(page.locator('.x6-node')).toHaveCount(11);
 const reloaded=await page.evaluate(()=>JSON.parse(localStorage.getItem('vto.plan.draft.v1')).plan);
 expect(reloaded.nodes).toEqual(draft.plan.nodes);expect(reloaded.edges).toEqual(draft.plan.edges);
 await expect(page.locator('.plans-dialog')).not.toBeVisible();
 await page.waitForTimeout(300);
 await page.screenshot({path:'../../work/ui-workflow.png',fullPage:true});
 expect(errors).toEqual([]);expect(external).toEqual([]);
 await page.request.delete(`/api/plans/${draft.plan.id}`);
});

test('空文本、不可识别、上传边界与取消分支',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'导入规格',exact:true}).click();
 await page.getByRole('button',{name:'开始分解',exact:true}).click();await expect(page.locator('.parse-error')).toContainText('请粘贴');
 await page.locator('#spec-text').fill('plain unsupported text');await page.getByRole('button',{name:'开始分解',exact:true}).click();await expect(page.locator('.parse-error')).toContainText('无法识别');
 await page.locator('input[type=file][accept=".md,.txt"]').setInputFiles({name:'large.md',mimeType:'text/markdown',buffer:Buffer.alloc(204801,65)});await expect(page.getByText('规格文件不能超过 200 KB')).toBeVisible();
 await page.locator('#spec-text').fill(LOGIN_SPEC);await page.getByRole('button',{name:'开始分解',exact:true}).click();
 await page.locator('label.el-checkbox').filter({has:page.getByRole('checkbox',{name:'选择 返回错误提示',exact:true})}).click();
 await page.getByRole('button',{name:'确认并生成画布',exact:true}).click();
 await expect(page.locator('.node-count')).toHaveText('10 节点 · 11 连线');
});
